# Цикл while True спрашивает у пользователя числа

# Если ввели 0 — выйти из цикла через break

# Если ввели отрицательное — пропустить через continue (не добавлять в сумму)

# Положительные — суммировать

# После выхода — вывести итоговую сумму

total = 0

while True:
    a = int(input("Введи число(0 - выход):"))
    if a == 0:
        break
    elif a < 0:
        continue
    else:
        total += a

print(f"Сумма положительных: {total}") 
    